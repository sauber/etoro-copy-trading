// Calculate daily return from previous day
const returns = (series: Series): Series => {
  return series.map((value, index) => {
    if (index === 0) return 0;
    return (value - series[index - 1]) / series[index - 1];
  }).slice(1);
};

// Calculate average of numbers
const average = (series: Series): number => {
  return series.reduce((a, b) => a + b, 0) / series.length;
};

// Calculate standard deviation of numbers
const stddev = (series: Series): number => {
  let total = 0;
  const avg = average(series);
  for (let i = 1; i < series.length; i++) {
    total += Math.pow(series[i] - series[i - 1] - avg, 2);
  }
  return Math.sqrt(total / (series.length - 1));
};

// Calculate Sharpe Ratio
const sharpe_ratio = (series: Series, annual_risk_free: number): number => {
  const daily_risk_free = annual_risk_free / 365;

  const r = returns(series);
  const avg = average(r);
  const std = stddev(r.filter((v) => v != 0));
  return (avg - daily_risk_free) / std;
};

// Calculate annualised Share Ratio asuming 365 bars per year
const annualised_sharpe_ratio = (series: Series, risk_free: number): number => {
  return sharpe_ratio(series, risk_free) * Math.sqrt(365);
};

